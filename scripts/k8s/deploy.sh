#!/usr/bin/env bash
# Deploys FlakeTracker to the cluster kubectl is currently pointed at. 
#
#   scripts/k8s/deploy.sh local                       # Kind cluster, locally built :local images
#   scripts/k8s/deploy.sh gke <TAG> [ANALYZER_TAG]    # GKE, images from Artifact Registry tagged <TAG>
#
# <TAG> is normally the git commit SHA the images were built from (scripts/gcp/build-push.sh
# prints it). Every image is tagged with a specific SHA, never :latest, which is what makes
# `kubectl rollout history` and `kubectl rollout undo` meaningful. ANALYZER_TAG lets the
# analyzer run a different build from the rest (e.g. the v2 scoring algorithm).
#
# Prerequisite: the Secrets exist (scripts/k8s/create-secrets.sh).
#
# It deploys in stages and waits for each, like Docker Compose did with depends_on:
#   1. namespace + settings    2. databases (wait until ready)
#   3. migrations (wait until complete)    4. everything else (wait for each rollout) 

set -euo pipefail

ENVIRONMENT="${1:?usage: deploy.sh local | deploy.sh gke <TAG> [ANALYZER_TAG]}"
NAMESPACE=flaketracker

# Work from the repo root no matter where the script is run from.
# BASH_SOURCE[0] is this script's own path; dirname + cd + pwd turns it into an absolute folder.
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
K8S="$REPO_ROOT/deploy/k8s"

# ---- 1. Build a small, throw-away "release" overlay describing exactly this release ----
# It sits on top of the environment overlay and sets (a) the image names/tags and
# (b) the change-cause note that `kubectl rollout history` displays.
# The folder is git-ignored: it is generated output, not source.
RELEASE_DIR="$K8S/overlays/_release"
mkdir -p "$RELEASE_DIR"

case "$ENVIRONMENT" in
  local)
    BASE_OVERLAY="../local"
    TAG="local"
    IMAGES_BLOCK=""          # the local images are already named flaketracker/<service>:local
    ;;
  gke)
    TAG="${2:?usage: deploy.sh gke <TAG> [ANALYZER_TAG]}"
    ANALYZER_TAG="${3:-$TAG}"
    BASE_OVERLAY="../gke"
    PROJECT_ID="$(gcloud config get-value project 2>/dev/null)"
    REGION="${REGION:-australia-southeast2}"
    AR_REPO="${AR_REPO:-flaketracker}"
    REGISTRY="$REGION-docker.pkg.dev/$PROJECT_ID/$AR_REPO"
    # kustomize's "images" list rewrites any image named flaketracker/<service> to the
    # registry path plus the tag, wherever it appears in the manifests.
    IMAGES_BLOCK="images:
  - {name: flaketracker/ingest,   newName: $REGISTRY/ingest,   newTag: \"$TAG\"}
  - {name: flaketracker/api,      newName: $REGISTRY/api,      newTag: \"$TAG\"}
  - {name: flaketracker/analyzer, newName: $REGISTRY/analyzer, newTag: \"$ANALYZER_TAG\"}
  - {name: flaketracker/web,      newName: $REGISTRY/web,      newTag: \"$TAG\"}
  - {name: flaketracker/migrate,  newName: $REGISTRY/migrate,  newTag: \"$TAG\"}"
    ;;
  *)
    echo "unknown environment '$ENVIRONMENT' (use: local or gke)" >&2
    exit 2
    ;;
esac

CHANGE_CAUSE="release $TAG to $ENVIRONMENT, $(date -u '+%Y-%m-%d %H:%M')Z"
[ "$ENVIRONMENT" = gke ] && [ "${ANALYZER_TAG:-$TAG}" != "$TAG" ] && CHANGE_CAUSE="$CHANGE_CAUSE (analyzer $ANALYZER_TAG)"

cat > "$RELEASE_DIR/kustomization.yaml" <<EOF
# GENERATED by scripts/k8s/deploy.sh. Do not edit; do not commit.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - $BASE_OVERLAY
$IMAGES_BLOCK
patches:
  - target: {kind: Deployment, labelSelector: "app.kubernetes.io/component=app"}
    patch: |-
      - op: replace
        path: /metadata/annotations/kubernetes.io~1change-cause
        value: "$CHANGE_CAUSE"
EOF

OVERLAY="$RELEASE_DIR"
echo "== Deploying '$ENVIRONMENT' ($CHANGE_CAUSE)"

# apply_component <component>: apply only the objects labelled app.kubernetes.io/component=<component>.
#   -k   build the manifests from a kustomize folder     -l   only objects with this label
apply_component() {
  kubectl apply -k "$OVERLAY" -l "app.kubernetes.io/component=$1"
}

# ---- 2. Namespace and shared settings ----
echo "== 1/4 namespace and settings"
apply_component config

# ---- 3. Databases: wait until each is accepting connections ----
echo "== 2/4 databases"
apply_component database
for db in ingest-db analyzer-db api-db; do
  # rollout status blocks until the StatefulSet's pod is Ready (its pg_isready probe passes).
  kubectl -n "$NAMESPACE" rollout status "statefulset/$db" --timeout=300s
done

# ---- 4. Migrations: create the tables, wait for them to finish ----
echo "== 3/4 migrations"
# A Job's pod template can't be changed once created, and each release may use a new
# image tag, so delete the previous Jobs and create fresh ones. Migrations are
# idempotent, so running them again is harmless.
kubectl -n "$NAMESPACE" delete job -l app.kubernetes.io/component=migrate --ignore-not-found --wait=true
apply_component migrate
# --for=condition=complete  wait until the Job's pod has run to success
kubectl -n "$NAMESPACE" wait --for=condition=complete job -l app.kubernetes.io/component=migrate --timeout=300s

# ---- 5. The rest: services, autoscalers, disruption budgets, Ingress / edge ----
echo "== 4/4 services"
kubectl apply -k "$OVERLAY"
for d in ingest api analyzer web; do
  kubectl -n "$NAMESPACE" rollout status "deployment/$d" --timeout=300s
done

echo
kubectl -n "$NAMESPACE" get pods -o wide
echo
if [ "$ENVIRONMENT" = gke ]; then
  echo "Ingress (the ADDRESS appears after a few minutes; the load balancer takes time to provision):"
  kubectl -n "$NAMESPACE" get ingress flaketracker
else
  echo "Open the app with:  kubectl -n $NAMESPACE port-forward svc/edge 8080:80   then  http://localhost:8080"
fi
